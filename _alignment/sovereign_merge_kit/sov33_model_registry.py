def main():
    import argparse
    parser = argparse.ArgumentParser(
        description='SOV33 Model Registry — top 100 open-source models',
    )
    parser.add_argument('cmd', nargs='?', choices=['list', 'tier', 'safe', 'brain', 'aggregate', 'save'], default='list')
    parser.add_argument('--tier', default='frontier', help='Filter by tier')
    parser.add_argument('--name', help='Brain name to look up')
    parser.add_argument('--brains', nargs='+', help='List of brain names to aggregate')
    parser.add_argument('--max', type=int, default=200, help='Max to list')
    args = parser.parse_args()

    if args.cmd == 'save':
        save_registry()
        sigil_emit({
            'hop': 'MODEL_REGISTRY_SAVED',
            'n_models': len(REGISTRY),
            'tiers': list({v['tier'] for v in REGISTRY.values()}),
            'n_sovereign_safe': sum(1 for v in REGISTRY.values() if v.get('sovereign_safe', False)),
            'care_floor': 0.95,
            'sovereign_mist_12_pillars_bound': True,
        })
        print(f"Saved {len(REGISTRY)} models to {REGISTRY_FILE}")
        return

    if args.cmd == 'list':
        print()
        print("=" * 90)
        print(f"SOV33 MODEL REGISTRY — {len(REGISTRY)} open-source models")
        print("=" * 90)
        print()
        for name, m in sorted(REGISTRY.items(), key=lambda x: -x[1].get('params_total_B', 0))[:args.max]:
            sf = '✓' if m.get('sovereign_safe', False) else '✗'
            print(f"  {sf} {name:25s} {m['tier']:12s} {m['params_active_B']:6.1f}/{m['params_total_B']:6.1f}B  {m.get('hf_id', '?'):50s}")
        return

    if args.cmd == 'tier':
        items = list_by_tier(args.tier)
        print(f"\n{args.tier.upper()} ({len(items)} models):")
        for name, m in items.items():
            sf = '✓' if m.get('sovereign_safe', False) else '✗'
            print(f"  {sf} {name:30s} {m['params_active_B']:6.1f}/{m['params_total_B']:6.1f}B  {m.get('best_for', ['?'])[0]}")
        return

    if args.cmd == 'safe':
        items = list_sovereign_safe()
        print(f"\nSOVEREIGN-SAFE ({len(items)} models — license clears for paid product):")
        for name, m in sorted(items.items(), key=lambda x: -x[1].get('params_total_B', 0)):
            print(f"  ✓ {name:30s} {m['params_active_B']:6.1f}/{m['params_total_B']:6.1f}B  {m.get('license', '?'):30s}  {m.get('best_for', ['?'])[0]}")
        return

    if args.cmd == 'brain':
        m = get_brain(args.name)
        if m:
            print(json.dumps(m, indent=2))
        else:
            print(f"No brain named {args.name}")
        return

    if args.cmd == 'aggregate':
        if not args.brains:
            # Default: all sovereign-safe frontier + production
            default_brains = [
                'llama_3_1_70b', 'qwen3_6_35b_a3b', 'mistral_large_123b',
                'mixtral_8x22b', 'qwen3_8b', 'qwen2_5_3b',
                'deepseek_v3', 'qwen3_235b', 'kimi_k2_6', 'mimo_v2_5_pro',
                'cohere_plus_104b', 'gemma_3_27b', 'gpt_oss_120b', 'phi4_14b',
                'nemotron_3_super_120b', 'qwen3_coder_next',
            ]
            args.brains = default_brains
        result = total_aggregate(args.brains)
        print(json.dumps(result, indent=2))
        return

    parser.print_help()


if __name__ == '__main__':
    main()