SIGIL_FILE = Path(_SOVDIR) / 'model_registry.sigil.jsonl'
SIGIL_FILE.parent.mkdir(parents=True, exist_ok=True)
REGISTRY_FILE = Path(_SOVDIR) / 'model_registry.json'


def sigil_emit(hop):
    chain = []
    if SIGIL_FILE.exists():
        for line in SIGIL_FILE.read_text().splitlines():
            if line.strip():
                chain.append(json.loads(line))
    prev = chain[-1]['digest'] if chain else '0' * 16
    payload = {**hop, 'prev_hash': prev}
    digest = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()[:16]
    signed = {**payload, 'digest': digest, 'ts': datetime.now(timezone.utc).isoformat()}
    with SIGIL_FILE.open('a') as f:
        f.write(json.dumps(signed) + '\n')
    return digest


def save_registry():
    REGISTRY_FILE.write_text(json.dumps(REGISTRY, indent=2))


def get_brain(name: str) -> dict:
    return REGISTRY.get(name, {})


def list_by_tier(tier: str) -> dict:
    return {k: v for k, v in REGISTRY.items() if v.get('tier') == tier}


def list_sovereign_safe() -> dict:
    return {k: v for k, v in REGISTRY.items() if v.get('sovereign_safe', False)}


def total_aggregate(names: list) -> dict:
    """Sum aggregate parameters for a list of brain names."""
    total_B = 0.0
    active_B = 0.0
    cost_per_call = 0.0
    latency_max = 0.0
    for name in names:
        if name not in REGISTRY:
            continue
        b = REGISTRY[name]
        total_B += b['params_total_B']
        active_B += b['params_active_B']
        cost_per_call += b.get('cost_per_call', 0)
        latency_max = max(latency_max, b.get('latency_s', 0))
    return {
        'brains': names,
        'n_brains': len(names),
        'total_aggregate_B': round(total_B, 1),
        'total_aggregate_T': round(total_B / 1000, 3),
        'total_active_B': round(active_B, 1),
        'cost_per_call': round(cost_per_call, 4),
        'latency_max_s': round(latency_max, 2),
        'pct_of_3_4T': round(min(100, total_B / 34.0), 2),
    }


