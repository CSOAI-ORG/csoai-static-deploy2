/**
 * attest-verify — external Ed25519 card verifier (Cloudflare Worker).
 *
 * Re-homes the estate's verifier off the billing-blocked Vercel endpoint onto
 * a free Cloudflare Worker. Verifies the Ed25519-SIGNED measurement cards
 * (from sovos-city chain.py / card_issuer) WITHOUT any secret — the whole point
 * of asymmetric signatures.
 *
 * A third party can POST any card and get an honest {valid, signer,
 * content_id_matches} without trusting us. This is what makes the signed-card
 * issuance leg verifiable externally — the thing all four attestation markets
 * sell.
 *
 * Verification model (must match chain.py exactly):
 *   body_recomputed  = canonical(JSON stringify with sorted keys, no spaces)
 *   content_id       = sha256(body_with_prev_epoch)
 *   valid            = Ed25519(pubkey).verify(signature, content_id)
 *
 * Endpoints:
 *   GET  /            -> service info
 *   POST /verify      -> body = card JSON { body, signature, pubkey, content_id }
 *   GET  /pubkey      -> the estate public key (kid: ed25519:...)
 */
// CF Workers expose WebCrypto (crypto.subtle) — Ed25519 + SHA-256 are native.
// No node:crypto (unavailable in Workers). Verification needs no secret.

async function canonicalStringify(obj) {
  // deterministic: sorted keys, no spaces, same as Python json.dumps(sort_keys,
  // separators=(",",":"), ensure_ascii=False) for the boolean/null/string/number
  // shapes that appear in cards.
  if (Array.isArray(obj)) {
    const parts = [];
    for (const v of obj) parts.push(await canonicalStringify(v));
    return "[" + parts.join(",") + "]";
  }
  if (obj && typeof obj === "object") {
    const keys = Object.keys(obj).sort();
    const parts = [];
    for (const k of keys) {
      const v = obj[k];
      if (v === undefined) continue;
      const ks = JSON.stringify(k);
      const vs = await canonicalStringify(v);
      parts.push(ks + ":" + vs);
    }
    return "{" + parts.join(",") + "}";
  }
  return JSON.stringify(obj);
}

async function sha256Hex(str) {
  const buf = new TextEncoder().encode(str);
  const digest = await crypto.subtle.digest("SHA-256", buf);
  return Array.from(new Uint8Array(digest)).map((b) => b.toString(16).padStart(2, "0")).join("");
}

async function verifyEd25519(pubkeyHex, sigHex, msgStr) {
  try {
    const keyBytes = new Uint8Array(
      pubkeyHex.match(/[0-9a-fA-F]{2}/g).map((b) => parseInt(b, 16))
    );
    const sigBytes = new Uint8Array(
      sigHex.match(/[0-9a-fA-F]{2}/g).map((b) => parseInt(b, 16))
    );
    const key = await crypto.subtle.importKey(
      "raw", keyBytes, { name: "Ed25519" }, false, ["verify"]
    );
    const ok = await crypto.subtle.verify(
      "Ed25519", key, sigBytes, new TextEncoder().encode(msgStr)
    );
    return ok;
  } catch (e) {
    return false;
  }
}

