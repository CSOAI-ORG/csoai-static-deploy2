function jsonResponse(obj, status = 200) {
  return new Response(JSON.stringify(obj, null, 2), {
    status,
    headers: {
      "Content-Type": "application/json",
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
      "Access-Control-Allow-Headers": "Content-Type",
    },
  });
}

export default {
  async fetch(request) {
    const url = new URL(request.url);

    if (request.method === "OPTIONS") {
      return jsonResponse({ ok: true });
    }

    // GET / -> service info
    if (request.method === "GET" && (url.pathname === "/" || url.pathname === "/health")) {
      return jsonResponse({
        service: "csoai-attest-verify",
        version: "1.0.0",
        scheme: "Ed25519 (FIPS-compatible asymmetric)",
        note: "external verification without secret — same model as chain.py",
      });
    }

    // GET /.well-known/did.json -> the committed did:web identity document
    if (request.method === "GET" && url.pathname === "/.well-known/did.json") {
      return new Response(JSON.stringify(DID_JSON, null, 2), {
        status: 200,
        headers: {
          "Content-Type": "application/did+ld+json",
          "Access-Control-Allow-Origin": "*",
          "Cache-Control": "public, max-age=300",
        },
      });
    }

    // POST /verify
    if (request.method === "POST" && url.pathname === "/verify") {
      let card;
      try {
        card = await request.json();
      } catch (e) {
        return jsonResponse({ valid: false, error: "invalid JSON body" }, 400);
      }
      if (!card || typeof card !== "object") {
        return jsonResponse({ valid: false, error: "card must be an object" }, 400);
      }

      const body = card.body;
      const signature = card.signature;
      const pubkey = card.pubkey || card.signer;   // card_issuer stores pubkey as `signer`
      const claimedContentId = card.content_id;

      if (!body || !signature || !pubkey) {
        return jsonResponse({
          valid: false,
          error: "card missing body/signature/pubkey",
          hint: "sanitised: only fully-formed Ed25519 cards verify",
        }, 400);
      }

      try {
        // 1. recompute canonical body -> content_id (match chain.py)
        const canon = await canonicalStringify(body);
        const recomputed = await sha256Hex(canon);

        // 2. verify the signature over the RECOMPUTED content id (not the claimed one)
        const sigOk = await verifyEd25519(pubkey, signature, recomputed);

        // 3. also confirm the claimed content_id matches (defence against a
        //    replayed card asserting a stale id)
        const cidMatch = recomputed === String(claimedContentId);

        return jsonResponse({
          valid: cidMatch && sigOk,
          signer: "ed25519:" + String(pubkey).slice(0, 16),
          content_id: recomputed,
          content_id_matches: cidMatch,
          signature_valid: sigOk,
          note: cidMatch && sigOk ? "card verified: measurement record intact" :
                "card FAILED verification: content or signature does not match",
        });
      } catch (e) {
        return jsonResponse({ valid: false, error: "verification error: " + e.message }, 500);
      }
    }

    return jsonResponse({ valid: false, error: "not found" }, 404);
  },
};
