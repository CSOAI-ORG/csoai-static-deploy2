def generate_notebook(repo_url: str = DEFAULT_REPO,
                      output_path: str | Path = DEFAULT_OUTPUT) -> Path:
    output_path = Path(output_path)
    notebook = build_notebook(repo_url)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(notebook, f, indent=1)
    print(f"Generated Gradient notebook: {output_path}")
    cell_count = len(notebook.get("cells", []))
    code_count = sum(1 for c in notebook["cells"] if c["cell_type"] == "code")
    print(f"  Cells: {cell_count} (code: {code_count})")
    return output_path


