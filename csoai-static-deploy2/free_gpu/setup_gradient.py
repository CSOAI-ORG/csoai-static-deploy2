def compute_sigil(content: str) -> str:
    return hashlib.sha256(content.encode()).hexdigest()[:16]


def main():
    parser = argparse.ArgumentParser(
        description="Generate Gradient/PaperSpace notebook for P100 training"
    )
    parser.add_argument("--output", type=str, default=str(DEFAULT_OUTPUT),
                        help=f"Output notebook path (default: {DEFAULT_OUTPUT})")
    parser.add_argument("--repo", type=str, default=DEFAULT_REPO,
                        help=f"Repository URL (default: {DEFAULT_REPO})")
    args = parser.parse_args()

    output_path = generate_notebook(args.repo, args.output)
    content = output_path.read_text()
    sigil = compute_sigil(content)
    print(f"  SHA-256 sigil: {sigil}")
    print()

    print_instructions()


if __name__ == "__main__":
    main()
