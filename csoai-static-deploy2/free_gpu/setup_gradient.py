def benchmark_model(model, tokenizer, domains):
    results = {}
    for domain, items in domains.items():
        correct = 0
        for question, expected in items:
            prompt = f"Answer briefly: {question}"
            inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
