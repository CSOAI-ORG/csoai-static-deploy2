def log(msg: str) -> None:
    ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
    print(f"[{ts}] {msg}", flush=True)


def verify_gpu() -> dict[str, Any]:
    """Check GPU availability and return device info."""
    try:
        import torch
    except ImportError:
        log("ERROR: torch not installed")
        return {"available": False}

    if not torch.cuda.is_available():
        log("ERROR: CUDA not available — T4 GPU required")
        return {"available": False}

    props = torch.cuda.get_device_properties(0)
    info = {
        "available": True,
        "name": torch.cuda.get_device_name(0),
        "memory_gb": round(props.total_mem / 1e9, 1),
        "torch_version": torch.__version__,
        "cuda_version": torch.version.cuda,
    }
    log(f"GPU: {info['name']}  {info['memory_gb']}GB  CUDA {info['cuda_version']}")
    return info


def load_model() -> Any:
    """Load sov5v2 in 4-bit quantization on the T4."""
    import torch
    from transformers import AutoTokenizer, AutoModelForCausalLM, BitsAndBytesConfig

    bnb_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_compute_dtype=torch.float16,
        bnb_4bit_use_double_quant=True,
        bnb_4bit_quant_type="nf4",
    )

    log(f"Loading {MODEL_NAME}...")
    t0 = time.time()
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME, trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_NAME,
        quantization_config=bnb_config,
        device_map="auto",
        trust_remote_code=True,
        torch_dtype=torch.float16,
    )
    elapsed = time.time() - t0
    log(f"Model loaded in {elapsed:.1f}s  params: {model.num_parameters():,}")
    return model, tokenizer


def benchmark_model(model: Any, tokenizer: Any) -> dict[str, Any]:
    """Run capability benchmarks across all domains."""
    import torch

    results: dict[str, float] = {}
    for domain, items in DOMAINS.items():
        correct = 0
        for question, expected in items:
            prompt = f"Answer briefly: {question}"
            inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
            with torch.no_grad():
                outputs = model.generate(
                    **inputs,
                    max_new_tokens=32,
                    temperature=0,
                    do_sample=False,
                    pad_token_id=tokenizer.eos_token_id,
                )
            response = tokenizer.decode(outputs[0], skip_special_tokens=True).lower()
            if expected.lower() in response:
                correct += 1
        results[domain] = correct / len(items)
    return results


def print_benchmark_table(scores: dict[str, float]) -> float:
    avg = sum(scores.values()) / len(scores)
    log("Benchmark Results:")
    print(f"{'Domain':20s} {'Score':>8s}")
    print("-" * 30)
    for domain, score in sorted(scores.items()):
        marker = "***" if score < 0.8 else "   "
        print(f"{marker} {domain:20s} {score*100:6.1f}%")
    print("-" * 30)
    print(f"{'Average':20s} {avg*100:6.1f}%")
    return avg


def generate_training_data(scores: dict[str, float]) -> list[dict[str, Any]]:
    """Generate chat-formatted training examples for weak domains."""
    import random

    weak_domains = [d for d, s in scores.items() if s < 0.8]
    log(f"Weak domains ({len(weak_domains)}): {weak_domains}")

    training_data: list[dict[str, Any]] = []
    for domain in weak_domains:
        if domain in DOMAINS:
            for question, answer in DOMAINS[domain]:
                training_data.append({
                    "messages": [
                        {"role": "user", "content": question},
                        {"role": "assistant", "content": answer},
                    ]
                })

    augmented: list[dict[str, Any]] = []
    for item in training_data:
        augmented.append(item)
        for prefix in ["Explain: ", "Define: ", "What is: "]:
            augmented.append({
                "messages": [
                    {"role": "user", "content": prefix + item["messages"][0]["content"]},
                    {"role": "assistant", "content": item["messages"][1]["content"]},
                ]
            })

    random.shuffle(augmented)
    log(f"Generated {len(augmented)} training examples from {len(weak_domains)} weak domains")
    return augmented


def run_training(model: Any, tokenizer: Any, train_data: list[dict[str, Any]]) -> str:
    """Run LoRA fine-tuning and return adapter path."""
    from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training, TaskType
    from transformers import TrainingArguments
    from trl import SFTTrainer
    from datasets import Dataset

    lora_config = LoraConfig(
        r=16,
        lora_alpha=32,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
        lora_dropout=0.1,
        bias="none",
        task_type=TaskType.CAUSAL_LM,
    )

    model = prepare_model_for_kbit_training(model)
    model = get_peft_model(model, lora_config)
    model.print_trainable_parameters()

    train_dataset = Dataset.from_list(train_data)
    adapter_path = CHECKPOINT_DIR / "sov33_lora_final"

    training_args = TrainingArguments(
        output_dir=str(CHECKPOINT_DIR),
        per_device_train_batch_size=4,
        gradient_accumulation_steps=4,
        learning_rate=2e-4,
        warmup_steps=10,
        num_train_epochs=3,
        logging_steps=5,
        save_steps=50,
        evaluation_strategy="no",
        save_strategy="steps",
        fp16=True,
        gradient_checkpointing=True,
        optim="paged_adamw_8bit",
        max_grad_norm=0.3,
        report_to="none" if not os.environ.get("WANDB_API_KEY") else "wandb",
        save_total_limit=2,
        remove_unused_columns=False,
    )

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        args=training_args,
        train_dataset=train_dataset,
        max_seq_length=512,
        dataset_text_field="messages",
        formatting_func=lambda x: tokenizer.apply_chat_template(
            x["messages"], tokenize=False, add_generation_prompt=False
        ),
    )

    log("Starting LoRA training on T4...")
    t0 = time.time()
    trainer.train()
    elapsed = time.time() - t0
    log(f"Training completed in {elapsed/60:.1f} minutes")

    adapter_path.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(str(adapter_path))
    tokenizer.save_pretrained(str(adapter_path))
    log(f"LoRA adapter saved to {adapter_path}")

    return str(adapter_path)


def upload_checkpoints(adapter_path: str) -> bool:
    """Upload checkpoints to S3-compatible storage."""
    bucket = os.environ.get("S3_BUCKET", "sov33-checkpoints")
    key_id = os.environ.get("AWS_ACCESS_KEY_ID")
    secret_key = os.environ.get("AWS_SECRET_ACCESS_KEY")

    if not (key_id and secret_key):
        log("AWS credentials not set — skipping S3 upload")
        return False

    try:
        import boto3
        session = boto3.Session(
            aws_access_key_id=key_id,
            aws_secret_access_key=secret_key,
        )
        s3 = session.client("s3")

        adapter_dir = Path(adapter_path)
        for fpath in adapter_dir.rglob("*"):
            if fpath.is_file():
                key = f"checkpoints/{fpath.relative_to(adapter_dir.parent)}"
                s3.upload_file(str(fpath), bucket, key)
                log(f"Uploaded {key} to s3://{bucket}")

        log(f"Checkpoints synced to S3 bucket: {bucket}")
        return True
    except Exception as e:
        log(f"S3 upload failed: {e}")
        return False


